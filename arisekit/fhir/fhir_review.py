"""Frozen, blinded clinical review packets without invented clinician judgments."""
from __future__ import annotations

import csv
from datetime import datetime
import hashlib
import json
from pathlib import Path

from arisekit.env.docker_fhir import digest
from arisekit.package import load_package

FIELDS = ("packet_sha256", "item_id", "reviewer_id", "credential", "specialty", "reviewed_at",
    "judgment", "task_clear", "reference_correct", "scorer_matches", "clinical_risk", "comment", "independent_attestation")
DIMENSIONS = ("task_clear", "reference_correct", "scorer_matches")


def prepare(package_path, output):
    package = load_package(package_path, verify_assets=True)
    from arisekit.fhir.fhir_workflow import binding_from_package
    binding = binding_from_package(package)
    root = Path(output)
    if root.exists():
        raise ValueError("Create the review packet in a new directory")
    root.mkdir(parents=True)
    inventory = []
    for item in package.items:
        opaque = "item-" + digest(item.to_dict())[:16]
        chart = binding.bundles[item.id]
        task = {"item_id": opaque, "task": item.prompt, "starting_chart": chart}
        (root / f"{opaque}-task.json").write_text(json.dumps(task, indent=2) + "\n")
        reference = {"item_id": opaque, "reference_origin": "AI-generated",
                     "reference_and_scoring": item.ground_truth}
        (root / f"{opaque}-reference.json").write_text(json.dumps(reference, indent=2) + "\n")
        inventory.append({"item_id": opaque, "source_item_sha256": digest(item.to_dict())})
    brief = package.manifest.provenance["fhir_brief"]
    (root / "brief.json").write_text(json.dumps(brief, indent=2) + "\n")
    (root / "instructions.md").write_text(
        "# Independent FHIR task review\n\n"
        "Review each task and starting chart first, without opening its reference file. "
        "Record your own expected answer or appropriate chart change in your notes. "
        "Then open the reference file and assess whether its answer, permitted changes and scoring predicates "
        "match the task. The reference was generated by AI. No model performance or model identity is included.\n\n"
        "Use yes, no or uncertain for task clarity, reference correctness and scorer alignment. "
        "Use valid, needs-revision or unreviewable for the overall judgment. "
        "Use none, minor, major or uncertain for clinical risk if the task were used in an evaluation. "
        "Explain any incorrect, unsupported, ambiguous, missing or unsafe clinical rule. Cite evidence when useful. "
        "Review the frozen output; do not repair it. Proposed repairs belong to a subsequent version.\n\n"
        "Complete reviewer ID, credential, specialty and review time for each rating. "
        "Set independent_attestation to yes only for your own independent human judgment. "
        "Keep individual ratings before any discussion or adjudication. Preserve disagreement and missing ratings. "
        "Leave fields blank until reviewed. The study owner must confirm reviewer eligibility and any required "
        "institutional determination before collecting reviews for research.\n"
    )
    files = {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(root.iterdir())}
    manifest = {"schema_version": "arisekit.fhir-clinical-packet.v1", "items": inventory, "files": files,
        "review_status": "awaiting-independent-human-review", "sampling": "complete-enumeration-of-frozen-package",
        "clinical_scope": brief["clinical_scope"], "reference_origin": "AI-generated"}
    manifest["packet_sha256"] = digest(manifest)
    (root / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    with (root / "ratings-template.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        for item in inventory:
            writer.writerow({"packet_sha256": manifest["packet_sha256"], "item_id": item["item_id"]})
    return manifest


def summarize(packet_path, ratings_path):
    root = Path(packet_path)
    manifest = json.loads((root / "manifest.json").read_text())
    if manifest["packet_sha256"] != digest({k: v for k, v in manifest.items() if k != "packet_sha256"}):
        raise ValueError("Clinical packet manifest checksum differs")
    for name, expected in manifest["files"].items():
        path = root / name
        if path.name != name or path.is_symlink() or hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise ValueError("Clinical packet content changed after freeze")
    items = {row["item_id"] for row in manifest["items"]}
    ratings, seen = [], set()
    with Path(ratings_path).open(newline="") as handle:
        reader = csv.DictReader(handle)
        if tuple(reader.fieldnames or ()) != FIELDS:
            raise ValueError("Use the frozen clinical rating columns")
        for row in reader:
            if not any(row.get(key) for key in FIELDS[2:]):
                continue
            if row["packet_sha256"] != manifest["packet_sha256"] or row["item_id"] not in items:
                raise ValueError("Rating belongs to a different frozen packet")
            if any(not row[key].strip() for key in FIELDS[2:] if key != "comment"):
                raise ValueError("Completed ratings need reviewer identity, credentials, time, decisions and attestation")
            if row["independent_attestation"] != "yes":
                raise ValueError("Clinical ratings require independent human attestation")
            if row["judgment"] not in {"valid", "needs-revision", "unreviewable"} or any(row[key] not in {"yes", "no", "uncertain"} for key in DIMENSIONS):
                raise ValueError("Invalid clinical judgment or dimension")
            if row["clinical_risk"] not in {"none", "minor", "major", "uncertain"}:
                raise ValueError("Invalid clinical risk rating")
            timestamp = datetime.fromisoformat(row["reviewed_at"].replace("Z", "+00:00"))
            if timestamp.tzinfo is None:
                raise ValueError("Clinical review time must include its time zone")
            identity = row["item_id"], row["reviewer_id"]
            if identity in seen:
                raise ValueError("Duplicate item/reviewer rating; retain revisions separately")
            seen.add(identity)
            ratings.append(row)
    reviewed = {row["item_id"] for row in ratings}
    return {"schema_version": "arisekit.fhir-clinical-review-summary.v1", "packet_sha256": manifest["packet_sha256"],
        "items": len(items), "reviewed_items": len(reviewed), "missing_items": sorted(items - reviewed),
        "reviewers": sorted({row["reviewer_id"] for row in ratings}), "ratings": ratings,
        "judgments": {label: sum(row["judgment"] == label for row in ratings) for label in ("valid", "needs-revision", "unreviewable")},
        "status": "no-clinical-judgments" if not ratings else "human-ratings-recorded",
        "claim": "Descriptive independent ratings of this frozen packet; no population-level clinical validity estimate or release gate"}
